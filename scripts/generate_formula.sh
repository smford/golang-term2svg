#!/usr/bin/env bash
# scripts/generate_formula.sh
# Generates a Homebrew Ruby formula from GoReleaser artifacts and checksums.
set -euo pipefail

DIST_DIR="${1:-dist}"
FORMULA_DIR="${2:-Formula}"
APP_NAME="term2svg"
CLASS_NAME="Term2svg"
MODULE="github.com/smford/golang-term2svg"
HOMEPAGE="https://${MODULE}"
DESCRIPTION="Render terminal commands, ANSI streams, tmux panes, and screen models to vector SVGs"

CHECKSUM_FILE="${DIST_DIR}/checksums.txt"

if [ ! -f "${CHECKSUM_FILE}" ]; then
  echo "Error: Checksum file not found at ${CHECKSUM_FILE}" >&2
  exit 1
fi

# Detect version from tag or checksum files
SAMPLE_ARCHIVE=$(grep "${APP_NAME}_" "${CHECKSUM_FILE}" | head -n 1 | awk '{print $2}')
# Format: term2svg_vX.Y.Z_os_arch.tar.gz
TAG=$(echo "${SAMPLE_ARCHIVE}" | sed -E "s/^${APP_NAME}_(v[0-9]+\.[0-9]+\.[0-9]+)_.*/\1/")
VERSION="${TAG#v}"

get_sha() {
  local pattern="$1"
  grep "${pattern}" "${CHECKSUM_FILE}" | awk '{print $1}'
}

DARWIN_ARM64_SHA=$(get_sha "${APP_NAME}_${TAG}_darwin_arm64.tar.gz")
DARWIN_AMD64_SHA=$(get_sha "${APP_NAME}_${TAG}_darwin_amd64.tar.gz")
LINUX_ARM64_SHA=$(get_sha "${APP_NAME}_${TAG}_linux_arm64.tar.gz")
LINUX_AMD64_SHA=$(get_sha "${APP_NAME}_${TAG}_linux_amd64.tar.gz")

mkdir -p "${FORMULA_DIR}"
FORMULA_PATH="${FORMULA_DIR}/${APP_NAME}.rb"

cat <<EOF > "${FORMULA_PATH}"
# typed: false
# frozen_string_literal: true

# This file was generated by scripts/generate_formula.sh. DO NOT EDIT.
class ${CLASS_NAME} < Formula
  desc "${DESCRIPTION}"
  homepage "${HOMEPAGE}"
  version "${VERSION}"
  license "MIT"

  on_macos do
    if Hardware::CPU.arm?
      url "https://${MODULE}/releases/download/${TAG}/${APP_NAME}_${TAG}_darwin_arm64.tar.gz"
      sha256 "${DARWIN_ARM64_SHA}"

      def install
        bin.install "${APP_NAME}"
      end
    end
    if Hardware::CPU.intel?
      url "https://${MODULE}/releases/download/${TAG}/${APP_NAME}_${TAG}_darwin_amd64.tar.gz"
      sha256 "${DARWIN_AMD64_SHA}"

      def install
        bin.install "${APP_NAME}"
      end
    end
  end

  on_linux do
    if Hardware::CPU.arm? && Hardware::CPU.is_64_bit?
      url "https://${MODULE}/releases/download/${TAG}/${APP_NAME}_${TAG}_linux_arm64.tar.gz"
      sha256 "${LINUX_ARM64_SHA}"

      def install
        bin.install "${APP_NAME}"
      end
    end
    if Hardware::CPU.intel?
      url "https://${MODULE}/releases/download/${TAG}/${APP_NAME}_${TAG}_linux_amd64.tar.gz"
      sha256 "${LINUX_AMD64_SHA}"

      def install
        bin.install "${APP_NAME}"
      end
    end
  end

  test do
    system "#{bin}/${APP_NAME}", "-version"
  end
end
EOF

echo "Generated Homebrew formula: ${FORMULA_PATH} for ${TAG}"
